# Build the agent bundle inside agent-build.
#
# Inputs (managed by agents.build.configure):
#   ~/agent-build/lock.json           versions and digests from agents/lock.yml
#   ~/agent-build/install-agents.sh   installer copied into the bundle
#
# Output:
#   ~/agent-bundles/agents-bundle-<UTC timestamp>.tar.gz
#   ~/agent-bundles/agents-bundle-<UTC timestamp>.tar.gz.sha256
#   ~/agent-bundles/latest.path       absolute path of the newest bundle
#   ~/agent-bundles/latest.sha256     sha256sum line for the newest bundle
#
# The bundle layout is:
#   node/node-v<version>-linux-x64/   pinned Node runtime
#   node/current -> node-v<version>-linux-x64
#   agents/<name>/<version>/          npm prefix per agent
#   debs/<package>.deb                pinned .deb agents
#   wrappers/<bin>                    /usr/local/bin launchers for npm agents
#   install.sh                        installer run as root in tpl-agents
#   manifest.json                     lock + build timestamp
#
# This script runs as user in agent-build. It downloads only from the pinned
# URLs in lock.json; the build NetVM is where any VPN/egress policy applies.

set -eu

WS="${AGENT_BUILD_DIR:-${HOME}/agent-build}"
BUNDLE="${WS}/bundle"
CACHE="${WS}/cache"
DEB_CACHE="${CACHE}/debs"
OUT="${AGENT_BUNDLE_DIR:-${HOME}/agent-bundles}"
LOCK="${WS}/lock.json"
INSTALLER="${WS}/install-agents.sh"

mkdir -p "$WS" "$DEB_CACHE"
exec > >(tee -a "${WS}/build.log") 2>&1

for f in "$LOCK" "$INSTALLER"; do
    [ -f "$f" ] || { echo "missing $f" >&2; exit 1; }
done
command -v jq >/dev/null || { echo "jq is required" >&2; exit 1; }
command -v curl >/dev/null || { echo "curl is required" >&2; exit 1; }
command -v sha256sum >/dev/null || { echo "sha256sum is required" >&2; exit 1; }
command -v tar >/dev/null || { echo "tar is required" >&2; exit 1; }
command -v xz >/dev/null || { echo "xz is required" >&2; exit 1; }

mkdir -p "$BUNDLE" "$CACHE" "$OUT"

node_version="$(jq -r '.node.version' "$LOCK")"
node_url="$(jq -r '.node.url' "$LOCK")"
node_sha="$(jq -r '.node.sha256' "$LOCK")"
node_tgz="${CACHE}/node-v${node_version}-linux-x64.tar.xz"

echo "==> Node ${node_version}"
if [ ! -f "$node_tgz" ]; then
    curl -fL --retry 3 --connect-timeout 15 -o "${node_tgz}.part" "$node_url"
    mv "${node_tgz}.part" "$node_tgz"
fi
printf '%s  %s\n' "$node_sha" "$node_tgz" | sha256sum -c -

rm -rf "${BUNDLE}/node"
mkdir -p "${BUNDLE}/node"
tar -xJf "$node_tgz" -C "${BUNDLE}/node"
ln -sfn "node-v${node_version}-linux-x64" "${BUNDLE}/node/current"

export PATH="${BUNDLE}/node/current/bin:${PATH}"
echo "    node $(node --version), npm $(npm --version)"

# Everything below is rebuilt from the lock; the previous published bundles
# remain untouched and are the rollback source.
rm -rf "${BUNDLE}/agents" "${BUNDLE}/debs" "${BUNDLE}/wrappers"
mkdir -p "${BUNDLE}/agents" "${BUNDLE}/debs" "${BUNDLE}/wrappers"

# Iterate as JSON entries. Process substitution keeps the loop in this shell,
# so `set -e` aborts the build on the first failure instead of only exiting a
# pipeline subshell.
while IFS= read -r entry; do
    get() { printf '%s' "$entry" | base64 -d | jq -r "$1"; }
    name="$(get '.key')"
    method="$(get '.value.method')"
    version="$(get '.value.version')"
    bin="$(get '.value.bin')"

    case "$method" in
        npm)
            package="$(get '.value.package')"
            ignore_scripts="$(get '.value.ignore_scripts')"
            prefix="${BUNDLE}/agents/${name}/${version}"
            mkdir -p "$prefix"
            npm_args=(--no-audit --no-fund)
            [ "$ignore_scripts" = "true" ] && npm_args+=(--ignore-scripts)
            echo "==> npm ${package}@${version}"
            npm install -g --prefix "$prefix" "${npm_args[@]}" "${package}@${version}"
            if [ ! -x "${prefix}/bin/${bin}" ]; then
                echo "ERROR: ${prefix}/bin/${bin} was not created" >&2
                exit 1
            fi
            cat > "${BUNDLE}/wrappers/${bin}" <<EOF
#!/bin/sh
# Generated by agents.build.run for ${package}@${version}
export PATH="/opt/agents-bundle/node/current/bin:\$PATH"
exec "/opt/agents-bundle/agents/${name}/${version}/bin/${bin}" "\$@"
EOF
            chmod 0755 "${BUNDLE}/wrappers/${bin}"
            ;;
        deb)
            url="$(get '.value.url')"
            sha="$(get '.value.sha256')"
            fname="$(basename "$url")"
            cached="${DEB_CACHE}/${fname}"
            deb="${BUNDLE}/debs/${fname}"
            echo "==> deb ${fname}"
            if [ -f "$cached" ] && ! printf '%s  %s\n' "$sha" "$cached" | sha256sum -c - >/dev/null 2>&1; then
                echo "    cached copy failed its digest, re-downloading"
                rm -f "$cached"
            fi
            if [ ! -f "$cached" ]; then
                curl -fL --retry 3 --connect-timeout 15 -o "${cached}.part" "$url"
                mv "${cached}.part" "$cached"
            fi
            printf '%s  %s\n' "$sha" "$cached" | sha256sum -c -
            cp "$cached" "$deb"
            ;;
        *)
            echo "ERROR: unknown method '${method}' for ${name}" >&2
            exit 1
            ;;
    esac
done < <(jq -r '.agents | to_entries[] | @base64' "$LOCK")

cp "$INSTALLER" "${BUNDLE}/install.sh"
chmod 0755 "${BUNDLE}/install.sh"

built_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
jq --arg built_at "$built_at" '. + {built_at: $built_at}' "$LOCK" \
    > "${BUNDLE}/manifest.json"

stamp="$(date -u +%Y%m%dT%H%M%SZ)"
outfile="${OUT}/agents-bundle-${stamp}.tar.gz"
tar -czf "$outfile" -C "$BUNDLE" .
sha256sum "$outfile" > "${outfile}.sha256"

printf '%s\n' "$outfile" > "${OUT}/latest.path"
cp "${outfile}.sha256" "${OUT}/latest.sha256"
ln -sfn "$(basename "$outfile")" "${OUT}/latest.tar.gz"

echo
echo "bundle: $outfile"
echo "sha256: $(awk '{print $1}' "${outfile}.sha256")"
echo "next:   apply agents.deliver in dom0"
